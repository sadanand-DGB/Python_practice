a,b  = "sadanand" , "yadav"  #assigning multiple values to multiple variables
name = a + " " + b         #concatenation of string
print(name)   # print the string
print(len(name))   # length of string
print(name[1])   # first character of string
print(name[0:5])   # first 5 characters of string
print(name.find("and"))   # find the index of substring
print(name.replace("sadanand yadav" , "sadanand"))   # replace substring
print(name.upper())   # convert to uppercase
print(name.capitalize())   # capitalize first letter